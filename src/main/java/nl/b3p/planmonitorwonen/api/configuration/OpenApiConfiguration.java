package nl.b3p.planmonitorwonen.api.configuration;

import static nl.b3p.planmonitorwonen.api.configuration.ApiVersionConfiguration.MAJOR_VERSION;
import static nl.b3p.planmonitorwonen.api.configuration.ApiVersionConfiguration.VERSION;

import io.swagger.v3.core.converter.ModelConverters;
import io.swagger.v3.core.util.Json;
import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.examples.Example;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.media.Content;
import io.swagger.v3.oas.models.media.MediaType;
import io.swagger.v3.oas.models.media.Schema;
import io.swagger.v3.oas.models.responses.ApiResponse;
import io.swagger.v3.oas.models.security.SecurityRequirement;
import io.swagger.v3.oas.models.security.SecurityScheme;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import nl.b3p.planmonitorwonen.api.model.ProblemDetailSchema;
import nl.b3p.planmonitorwonen.api.validation.AantallenValidator;
import nl.b3p.planmonitorwonen.api.validation.EnumValues;
import org.springdoc.core.customizers.OpenApiCustomizer;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.context.annotation.Profile;
import org.springframework.core.io.ClassPathResource;

/**
 * The parts of the OpenAPI documentation which are not generated by springdoc from the controllers and models: the
 * general description, the shared error responses, the example planregistratie and the enum values from the database.
 */
@Configuration
public class OpenApiConfiguration {
  /** Shared error responses, to reference with the {@code ref} of an {@code @ApiResponse} annotation. */
  public static final String UNAUTHORIZED = "Unauthorized";

  public static final String FORBIDDEN = "Forbidden";

  public static final String NOT_FOUND = "NotFound";

  /** Tag for the endpoints only the web application needs, see {@link #WEBAPP_TAG_DESCRIPTION}. */
  public static final String WEBAPP_TAG = "Webapplicatie";

  public static final String WEBAPP_TAG_DESCRIPTION = "Hulpfuncties voor de webapplicatie van Planmonitor Wonen. Een"
      + " client die planregistraties aanlevert heeft deze niet nodig: de server vult `provincie`, `regio` en"
      + " `beoogdWoonmilieuAbf13` zelf in op basis van de gemeente en de geometrie, en de gemeentes waarvoor de"
      + " gebruiker planregistraties mag aanleveren staan in `gemeentes` van `GET /user`.";

  public static final String PLANREGISTRATIE_EXAMPLE = "#/components/examples/Planregistratie";

  /** Name of the security scheme for the session cookie of the Tailormap login, required for all endpoints. */
  static final String SESSION_SECURITY_SCHEME = "session";

  public static final String PROBLEM_JSON = "application/problem+json";

  static final String DESCRIPTION_RESOURCE = "openapi/description.md";

  /** A valid planregistratie, used as example request body. Checked to be valid by a unit test. */
  public static final String PLANREGISTRATIE_EXAMPLE_RESOURCE = "openapi/planregistratie-example.json";

  /** The Planregistratie properties with the values of an enum type in the database. */
  private static final Map<String, String> PLANREGISTRATIE_ENUM_TYPES = Map.of(
      "plantype", EnumValues.PLANTYPE,
      "statusPlanologisch", EnumValues.STATUS_PLANOLOGISCH,
      "vertrouwelijkheid", EnumValues.VERTROUWELIJKHEID,
      "opdrachtgeverType", EnumValues.OPDRACHTGEVER_TYPE,
      "statusProject", EnumValues.STATUS_PROJECT,
      "beoogdWoonmilieuAbf13", EnumValues.BEOOGD_WOONMILIEU_ABF13);

  @Bean
  public OpenAPI openAPI() throws IOException {
    @SuppressWarnings("rawtypes")
    Map<String, Schema> problemDetailSchemas =
        ModelConverters.getInstance(true).readAll(ProblemDetailSchema.class);
    Content problemDetail =
        new Content().addMediaType(PROBLEM_JSON, new MediaType().schema(new Schema<>().$ref("ProblemDetail")));

    return new OpenAPI()
        .info(new Info().title("Planmonitor Wonen API").version(VERSION).description(description()))
        .addSecurityItem(new SecurityRequirement().addList(SESSION_SECURITY_SCHEME))
        .components(new Components()
            .addSecuritySchemes(
                SESSION_SECURITY_SCHEME,
                new SecurityScheme()
                    .type(SecurityScheme.Type.APIKEY)
                    .in(SecurityScheme.In.COOKIE)
                    .name("SESSION")
                    .description("Sessie-cookie van het inloggen bij Tailormap, zie Inloggen"))
            .schemas(problemDetailSchemas)
            .addResponses(
                UNAUTHORIZED,
                new ApiResponse()
                    .description("Niet ingelogd of de sessie is verlopen")
                    .content(problemDetail))
            .addResponses(
                FORBIDDEN,
                new ApiResponse()
                    .description(
                        "Geen toegang: de gebruiker heeft geen autorisatie voor de gemeente van de"
                            + " planregistratie of voor Planmonitor Wonen")
                    .content(problemDetail))
            .addResponses(
                NOT_FOUND,
                new ApiResponse()
                    .description(
                        "Planregistratie niet gevonden, of van een gemeente waarvoor de gebruiker geen"
                            + " autorisatie heeft")
                    .content(problemDetail))
            .addExamples(
                "Planregistratie",
                new Example()
                    .summary("Planregistratie met aantallen")
                    .value(readJson(PLANREGISTRATIE_EXAMPLE_RESOURCE))));
  }

  /**
   * Sets the enum values read from the database on the model properties. This can't be done with
   * {@code @Schema(allowableValues)} without duplicating the values of the database schema.
   */
  @Bean
  @Profile("!test")
  public OpenApiCustomizer enumValuesCustomizer(EnumValues enumValues) {
    return openApi -> setEnumValues(openApi, enumValues);
  }

  /** The swagger models use raw types for the properties of a schema. */
  @SuppressWarnings({"rawtypes", "unchecked"})
  private static void setEnumValues(OpenAPI openApi, EnumValues enumValues) {
    Map<String, Schema> schemas = openApi.getComponents().getSchemas();

    Map<String, Schema> planregistratie = schemas.get("Planregistratie").getProperties();
    PLANREGISTRATIE_ENUM_TYPES.forEach(
        (property, enumType) -> setEnum(planregistratie.get(property), enumValues.get(enumType)));
    setEnum(planregistratie.get("knelpuntenMeerkeuze").getItems(), enumValues.get(EnumValues.KNELPUNTEN_MEERKEUZE));

    Map<String, Schema> aantallen = schemas.get("Aantallen").getProperties();
    AantallenValidator.GROEP_ENUM_TYPES.forEach(
        (groep, enumType) -> setCategorieen(aantallen.get(groep), enumValues.get(enumType)));
  }

  @SuppressWarnings("unchecked")
  private static void setEnum(Schema<?> schema, List<String> values) {
    ((Schema<String>) schema).setEnum(new ArrayList<>(values));
  }

  /**
   * Replaces the additionalProperties of a categorie group map with a property for each categorie, so the possible
   * keys are visible in the documentation.
   */
  @SuppressWarnings("rawtypes")
  private static void setCategorieen(Schema<?> groep, List<String> categorieen) {
    Map<String, Schema> properties = new LinkedHashMap<>();
    for (String categorie : categorieen) {
      properties.put(categorie, new Schema<>().$ref("Aantal"));
    }
    groep.setProperties(properties);
    groep.setAdditionalProperties(false);
  }

  private static String description() throws IOException {
    return new ClassPathResource(DESCRIPTION_RESOURCE)
        .getContentAsString(StandardCharsets.UTF_8)
        .replace("{majorVersion}", MAJOR_VERSION)
        .replace("{version}", VERSION);
  }

  private static Object readJson(String resource) throws IOException {
    return Json.mapper()
        .readValue(new ClassPathResource(resource).getContentAsString(StandardCharsets.UTF_8), Object.class);
  }
}
